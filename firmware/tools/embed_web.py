#!/usr/bin/env python3
"""Embed web/index.html into the firmware as a gzipped byte array (WebPage.h).
Run after changing the dashboard:   python firmware/tools/embed_web.py
"""
import gzip, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "web", "index.html")
DST = os.path.join(ROOT, "firmware", "MandalaPlotterESP32", "WebPage.h")

html = open(SRC, "rb").read()
gz = gzip.compress(html, compresslevel=9, mtime=0)
ver = re.search(rb'version:\s*"([^"]+)"', html)
ver = ver.group(1).decode() if ver else "?"
lines = []
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
with open(DST, "w", newline="\n") as f:
    f.write("// GENERATED by firmware/tools/embed_web.py from web/index.html - do not edit by hand.\n")
    f.write("#pragma once\n#include <Arduino.h>\n\n")
    f.write(f'#define WEB_PAGE_VERSION "{ver}"\n')
    f.write(f"const size_t WEB_PAGE_GZ_LEN = {len(gz)};\n")
    f.write("const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n")
print(f"web/index.html v{ver}: {len(html)} bytes -> {len(gz)} bytes gzipped -> {os.path.relpath(DST, ROOT)}")
